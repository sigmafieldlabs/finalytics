#!/usr/bin/env python3
"""Generate the Python and JavaScript API references from the shipped package sources.

    python3 scripts/reference_docs.py          write docs/reference/{python,javascript}.md
    python3 scripts/reference_docs.py --check  fail if those files are not current

The Python reference reads public classes, functions, methods and dataclasses from the typed
package with the AST, so it needs neither an installed package nor imports. The JavaScript
reference reads the JSDoc and declarations in the npm package's .d.ts files. scripts/guides.py
runs this check with the guides, and --record refreshes the generated documents.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
PY = ROOT / "bindings" / "python" / "python" / "finalytics"
WASM = ROOT / "bindings" / "wasm" / "pkg"

PYTHON_MODULES = [
    ("finalytics.assets", PY / "assets.py"),
    ("finalytics.portfolio", PY / "portfolio.py"),
    ("finalytics.performance", PY / "performance.py"),
    ("finalytics.screening", PY / "screening.py"),
    ("finalytics.datasets", PY / "datasets.py"),
    ("finalytics.reports", PY / "reports.py"),
    ("finalytics.risk", PY / "risk.py"),
    ("finalytics.opt", PY / "opt.py"),
    ("finalytics.pandas", PY / "pandas.py"),
    ("finalytics.errors", PY / "_errors.py"),
    ("finalytics.printing", PY / "_printing.py"),
    ("finalytics.types", PY / "_types.py"),
]
JAVASCRIPT_MODULES = [
    ("finalytics", WASM / "finalytics.d.ts"),
    ("finalytics/client.js", WASM / "client.d.ts"),
]
GUIDES = {
    "Assets": "how-finalytics-works",
    "Portfolio": "your-first-portfolio",
    "Universe": "screen-a-universe",
    "Performance": "measure-performance",
}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def clean_doc(text: str | None) -> str:
    """Keep the package's wording while translating Sphinx roles and literal blocks to Markdown."""
    if not text:
        return "No additional description in the package source."
    found = text.strip()
    found = re.sub(r":(?:class|meth|func|mod|data|exc|attr):`~?([^`]+)`", r"`\1`", found)
    found = found.replace("``", "`")
    source = found.splitlines()
    lines: list[str] = []
    index = 0
    while index < len(source):
        line = source[index]
        literal = line.strip() == "::" or line.rstrip().endswith("::")
        following = index + 1
        while following < len(source) and not source[following].strip():
            following += 1
        if not literal or following >= len(source) or not source[following].startswith("    "):
            lines.append(line)
            index += 1
            continue
        if line.strip() != "::":
            lines.append(line.rstrip()[:-2] + ":")
        lines += ["", "```python"]
        index = following
        block = []
        while index < len(source):
            line = source[index]
            if line.strip() and not line.startswith("    "):
                break
            block.append(line[4:] if line.startswith("    ") else "")
            index += 1
        lines += block + ["```", ""]
    return "\n".join(lines).strip()


def signature(node: ast.FunctionDef | ast.AsyncFunctionDef, name: str | None = None) -> str:
    args = ast.unparse(node.args)
    result = f"def {name or node.name}({args})"
    if node.returns is not None:
        result += f" -> {ast.unparse(node.returns)}"
    return result


def python_symbol(node: ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef,
                  module: str, parent: str = "") -> tuple[list[str], dict[str, str]]:
    name = f"{parent}{node.name}"
    lines = [f'<a id="{slug(name)}"></a>', "", f"### {name}", ""]
    if isinstance(node, ast.ClassDef):
        bases = [ast.unparse(base) for base in node.bases]
        keywords = [f"{k.arg}={ast.unparse(k.value)}" for k in node.keywords if k.arg]
        suffix = f"({', '.join(bases + keywords)})" if bases or keywords else ""
        lines += [f"```python\nclass {node.name}{suffix}\n```", ""]
    else:
        lines += [f"```python\n{signature(node)}\n```", ""]
    lines += [clean_doc(ast.get_docstring(node)), ""]
    entry = {
        "name": name,
        "kind": "class" if isinstance(node, ast.ClassDef) else "function",
        "module": module,
        "anchor": slug(name),
    }
    return lines, entry


def python_reference() -> tuple[str, list[dict[str, object]]]:
    lines = [
        "# Python API reference",
        "",
        "Generated from the public typed package's classes, functions, methods and docstrings.",
        "The signatures and wording are those of this release; do not edit this file by hand.",
        "",
    ]
    documents = []
    for module, path in PYTHON_MODULES:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        lines += [f"## {module}", "", clean_doc(ast.get_docstring(tree)), ""]
        entries = []
        for node in tree.body:
            if not isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if node.name.startswith("_"):
                continue
            block, entry = python_symbol(node, module)
            lines += block
            entries.append(entry)
            if isinstance(node, ast.ClassDef):
                for method in node.body:
                    if not isinstance(method, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        continue
                    if method.name.startswith("_") and method.name != "__init__":
                        continue
                    block, method_entry = python_symbol(
                        method, module, parent=f"{node.name}."
                    )
                    lines += block
                    entries.append(method_entry)
        documents.append({
            "module": module,
            "source": str(path.relative_to(ROOT)),
            "symbols": entries,
        })
    return "\n".join(lines).rstrip() + "\n", documents


def comment(lines: list[str]) -> str:
    if not lines:
        return "No additional description in the package source."
    found = []
    for line in lines:
        if line.strip() == "*/":
            continue
        line = re.sub(r"^\s*/\*\* ?", "", line)
        line = re.sub(r"^\s*\* ?", "", line)
        line = re.sub(r"\s*\*/$", "", line)
        found.append(line)
    return "\n".join(found).strip() or "No additional description in the package source."


DECLARATION = re.compile(
    r"^export\s+(?:(?:declare|default)\s+)?(interface|class|type|enum|function|const)\s+"
    r"([A-Za-z_$][\w$]*)"
)


def declarations(path: Path) -> list[tuple[str, str, str, str]]:
    """(name, kind, documentation, declaration), including overloads in source order."""
    source = path.read_text(encoding="utf-8").splitlines()
    found = []
    docs: list[str] = []
    for index, line in enumerate(source):
        if line.strip().startswith("/**"):
            docs = [line]
            while not docs[-1].strip().endswith("*/") and docs[-1].strip() != "*/":
                docs.append(source[len(docs) + index])
            continue
        match = DECLARATION.match(line)
        if not match:
            if line.strip() and not line.strip().startswith("*") and not line.strip().startswith("//"):
                docs = []
            continue
        kind, name = match.groups()
        if line.startswith("export default function"):
            name = "init"
        block = [line]
        if kind in {"interface", "class", "enum"}:
            depth = line.count("{") - line.count("}")
            while depth > 0:
                next_line = source[index + len(block)]
                block.append(next_line)
                depth += next_line.count("{") - next_line.count("}")
        else:
            while not block[-1].rstrip().endswith((";", "}")):
                block.append(source[index + len(block)])
        # Internal wasm-bindgen runtime symbols can include compiler-dependent hashes. They are
        # not the package's public API and must not make the generated reference nondeterministic.
        declaration = "\n".join(
            line for line in block
            if not re.match(r"^\s*(?:readonly\s+)?(?:__\w+|wasm_bindgen__)\w+\s*:", line)
        )
        found.append((name, kind, comment(docs), declaration))
        docs = []
    return found


def javascript_reference() -> tuple[str, list[dict[str, object]]]:
    lines = [
        "# JavaScript and TypeScript API reference",
        "",
        "Generated from the npm package's TypeScript declarations and their JSDoc. Overloads",
        "remain together, and the declaration text is that of this release; do not edit by hand.",
        "",
    ]
    documents = []
    for module, path in JAVASCRIPT_MODULES:
        lines += [f"## {module}", ""]
        grouped: dict[str, dict[str, object]] = {}
        for name, kind, docs, declaration in declarations(path):
            item = grouped.setdefault(name, {
                "name": name,
                "kind": kind,
                "docs": docs,
                "declarations": [],
            })
            item["declarations"].append(declaration)  # type: ignore[attr-defined]
        entries = []
        for name, item in grouped.items():
            anchor = slug(f"{module}-{name}")
            lines += [
                f'<a id="{anchor}"></a>',
                "",
                f"### {name}",
                "",
                str(item["docs"]),
                "",
                f"```typescript\n{chr(10).join(item['declarations'])}\n```",  # type: ignore[index]
                "",
            ]
            entries.append({
                "name": name,
                "kind": item["kind"],
                "module": module,
                "anchor": anchor,
            })
        documents.append({
            "module": module,
            "source": str(path.relative_to(ROOT)),
            "symbols": entries,
        })
    return "\n".join(lines).rstrip() + "\n", documents


def generated() -> dict[str, str]:
    python, python_modules = python_reference()
    javascript, javascript_modules = javascript_reference()
    index = {
        "generatedBy": "scripts/reference_docs.py",
        "documents": [
            {
                "id": "python-api",
                "title": "Python API reference",
                "description": "Classes, functions, methods, options and result types from the typed Python package.",
                "file": "python.md",
                "source": "docs/reference/python.md",
                "modules": python_modules,
            },
            {
                "id": "javascript-api",
                "title": "JavaScript and TypeScript API reference",
                "description": "Functions, classes, interfaces, options and result types from the npm package declarations.",
                "file": "javascript.md",
                "source": "docs/reference/javascript.md",
                "modules": javascript_modules,
            },
        ],
    }
    return {
        "python.md": python,
        "javascript.md": javascript,
        "index.json": json.dumps(index, indent=2) + "\n",
    }


def sync(write: bool, allow_missing_javascript: bool = False) -> list[str]:
    problems = []
    OUT.mkdir(parents=True, exist_ok=True)
    if allow_missing_javascript and not (WASM / "finalytics.d.ts").exists():
        # The Pyodide-only workflow has no npm build. Check Python there, not a missing artifact.
        documents = {"python.md": python_reference()[0]}
    else:
        documents = generated()
    for name, text in documents.items():
        path = OUT / name
        if write:
            path.write_text(text, encoding="utf-8")
            continue
        if not path.exists():
            problems.append(f"{path.relative_to(ROOT)} does not exist: run scripts/reference_docs.py")
            continue
        recorded = path.read_text(encoding="utf-8")
        if recorded != text:
            difference = "".join(difflib.unified_diff(
                recorded.splitlines(keepends=True), text.splitlines(keepends=True),
                fromfile="recorded", tofile="generated", n=2,
            ))
            problems.append(
                f"{path.relative_to(ROOT)} is not current: run scripts/reference_docs.py\n"
                + difference[:6000]
            )
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    problems = sync(write=not args.check)
    for problem in problems:
        print(f"error: {problem}")
    if problems:
        return 1
    print("reference docs " + ("checked" if args.check else "generated"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
