"""Generate the Python and TypeScript type declarations from the JSON Schema.

``schema/finalytics.schema.json`` is written from the Rust types by ``cargo run -p
finalytics-codegen``. This script turns it into:

- ``bindings/python/python/finalytics/_types.py``: frozen dataclasses, with the Rust doc comments
  as docstrings, and the tables the package uses to convert them to and from JSON;
- ``bindings/wasm/types.d.ts``: TypeScript declarations, included in the npm package's
  ``finalytics.d.ts``.

Usage:

    python scripts/generate-types.py           # write the files
    python scripts/generate-types.py --check   # fail if they are out of date

The script uses only the standard library.
"""

from __future__ import annotations

import json
import keyword
import pathlib
import sys
import textwrap

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema/finalytics.schema.json"
PYTHON = ROOT / "bindings/python/python/finalytics/_types.py"
TYPESCRIPT = ROOT / "bindings/wasm/types.d.ts"
HEADER = "Generated by scripts/generate-types.py from schema/finalytics.schema.json. Do not edit."

# Scalars written as strings, with their Python types.
SCALARS = {
    "Date": ("datetime.date", "string", "A date in ISO 8601 form, such as \"2026-11-02\"."),
    "Decimal": ("decimal.Decimal", "string", "An exact decimal number, written as a string such as \"201.50\"."),
    "Currency": ("str", "string", "An ISO 4217 currency code, such as \"USD\"."),
    "InstrumentId": ("str", "string", "An instrument's identifier, such as \"AAPL\"."),
    "AccountId": ("str", "string", "An account's identifier."),
    "TransactionId": ("str", "string", "A transaction's identifier."),
    "LotId": ("str", "string", "A tax lot's identifier."),
}

# Python class names for the variants of tagged unions, where the tag alone would be unclear or
# would clash with another name. Other variants take the tag in PascalCase.
VARIANT_NAMES = {
    "HoldingKey": {"instrument": "InstrumentHolding", "cash": "CashHolding"},
    "Effect": {"set_lot": "LotSet", "close_lot": "LotClosed", "cash": "CashChange"},
    "Allocation": {"trade": "TradeAllocation", "income": "IncomeAllocation", "exchange": "ExchangeAllocation"},
    "Prior": {"market": "MarketPrior", "returns": "ReturnsPrior"},
    "ShockSource": {
        "instrument": "InstrumentSource",
        "group": "GroupSource",
        "factor": "FactorSource",
        "history": "HistorySource",
        "proxy": "ProxySource",
        "cash": "CashSource",
        "none": "NoSource",
    },
}

# For a type whose own fields are flattened together with a tagged union, the name of the Python
# field holding the union, and the union's name.
FLATTENED = {"Transaction": ("kind", "TransactionKind")}


def pascal(tag: str) -> str:
    return "".join(part.capitalize() for part in tag.split("_"))


def ref_name(schema: dict) -> str | None:
    ref = schema.get("$ref")
    return ref.rsplit("/", 1)[1] if ref else None


def tag_of(variants: list[dict]) -> str | None:
    """The property every variant fixes with a constant: the union's tag."""
    common = None
    for v in variants:
        consts = {k for k, p in v.get("properties", {}).items() if "const" in p}
        common = consts if common is None else common & consts
    return sorted(common)[0] if common else None


def is_string_enum(schema: dict) -> bool:
    if "enum" in schema:
        return True
    variants = schema.get("oneOf", [])
    return bool(variants) and all("const" in v and v.get("type") == "string" for v in variants)


def string_values(schema: dict) -> list[str]:
    if "enum" in schema:
        return list(schema["enum"])
    return [v["const"] for v in schema["oneOf"]]


def nullable(schema: dict) -> tuple[dict, bool]:
    """The schema without a `null` alternative, and whether it had one."""
    t = schema.get("type")
    if isinstance(t, list) and "null" in t:
        rest = [x for x in t if x != "null"]
        return {**schema, "type": rest[0] if len(rest) == 1 else rest}, True
    for key in ("anyOf", "oneOf"):
        options = schema.get(key)
        if options and any(o.get("type") == "null" for o in options):
            others = [o for o in options if o.get("type") != "null"]
            if len(others) == 1:
                merged = {k: v for k, v in schema.items() if k != key}
                return {**merged, **others[0]}, True
    return schema, False


def doc(text: str | None) -> str:
    return (text or "").strip()


# --------------------------------------------------------------------------------------------
# TypeScript


def ts_type(schema: dict) -> str:
    inner, null = nullable(schema)
    text = ts_inner(inner)
    return f"{text} | null" if null else text


def ts_inner(schema: dict) -> str:
    name = ref_name(schema)
    if name:
        return name
    if "const" in schema:
        return json.dumps(schema["const"])
    if is_string_enum(schema):
        return " | ".join(json.dumps(v) for v in string_values(schema))
    t = schema.get("type")
    if t == "array" and "prefixItems" in schema:
        return "[" + ", ".join(ts_type(i) for i in schema["prefixItems"]) + "]"
    if t == "array":
        item = ts_type(schema.get("items", {}))
        return f"({item})[]" if "|" in item else f"{item}[]"
    if t == "object" and "properties" not in schema:
        value = schema.get("additionalProperties", {})
        return f"Record<string, {ts_type(value) if value else 'unknown'}>"
    if t in ("number", "integer"):
        return "number"
    if t == "string":
        return "string"
    if t == "boolean":
        return "boolean"
    if "oneOf" in schema:
        return " | ".join(ts_object(v) for v in schema["oneOf"])
    if "properties" in schema:
        return ts_object(schema)
    return "unknown"


def jsdoc(text: str, indent: str) -> list[str]:
    text = doc(text)
    if not text:
        return []
    lines = text.split("\n")
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *[f"{indent} * {line}".rstrip() for line in lines], f"{indent} */"]


def ts_fields(schema: dict, indent: str) -> list[str]:
    required = set(schema.get("required", []))
    out = []
    for key, prop in schema.get("properties", {}).items():
        out += jsdoc(prop.get("description", ""), indent)
        optional = "" if key in required else "?"
        out.append(f"{indent}{key}{optional}: {ts_type(prop)};")
    return out


def ts_object(schema: dict) -> str:
    fields = ts_fields(schema, "    ")
    if not fields:
        return "{}"
    return "{\n" + "\n".join(fields) + "\n  }"


def typescript(defs: dict) -> str:
    out = [f"// {HEADER}", ""]
    for name in sorted(defs):
        schema = defs[name]
        out += jsdoc(schema.get("description", ""), "")
        if name in SCALARS:
            out.append(f"export type {name} = string;")
        elif is_string_enum(schema):
            out.append(f"export type {name} = {ts_inner(schema)};")
        elif "oneOf" in schema and "properties" in schema:
            variants = "\n  | ".join(ts_object(v) for v in schema["oneOf"])
            fields = "\n".join(ts_fields(schema, "  "))
            out.append(f"export type {name} = {{\n{fields}\n}} & (\n  | {variants}\n);")
        elif "oneOf" in schema:
            variants = "\n  | ".join(ts_object(v) for v in schema["oneOf"])
            out.append(f"export type {name} =\n  | {variants};")
        elif "properties" in schema:
            out.append(f"export interface {name} {{")
            out += ts_fields(schema, "  ")
            out.append("}")
        else:
            out.append(f"export type {name} = {ts_type(schema)};")
        out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------------------------
# Python


class Python:
    def __init__(self, defs: dict):
        self.defs = defs
        self.unions: dict[str, tuple[str, dict[str, str]]] = {}
        self.classes: dict[str, str] = {}
        self.blocks: list[str] = []
        self.flattened: dict[str, tuple[str, str]] = {}

    def annotation(self, schema: dict) -> str:
        inner, null = nullable(schema)
        text = self.inner(inner)
        return f"{text} | None" if null else text

    def inner(self, schema: dict) -> str:
        name = ref_name(schema)
        if name:
            return SCALARS[name][0] if name in SCALARS else name
        if is_string_enum(schema):
            return "Literal[" + ", ".join(json.dumps(v) for v in string_values(schema)) + "]"
        t = schema.get("type")
        if t == "array" and "prefixItems" in schema:
            return "tuple[" + ", ".join(self.annotation(i) for i in schema["prefixItems"]) + "]"
        if t == "array":
            return f"list[{self.annotation(schema.get('items', {}))}]"
        if t == "object" and "properties" not in schema:
            value = schema.get("additionalProperties")
            return f"dict[str, {self.annotation(value) if value else 'object'}]"
        return {"number": "float", "integer": "int", "string": "str", "boolean": "bool"}.get(t, "object")

    def default(self, prop: dict, annotation: str) -> str | None:
        """The Python default for a field that may be left out, or None if it is required."""
        if "default" in prop:
            value = prop["default"]
            expression = self.value(prop, value)
            if value == []:
                return "field(default_factory=list)"
            if value == {}:
                return "field(default_factory=dict)"
            if isinstance(value, (list, dict)) or ref_name(prop) == "Decimal":
                return f"field(default_factory=lambda: {expression})"
            return expression
        if annotation.endswith("| None"):
            return "None"
        if annotation.startswith("list["):
            return "field(default_factory=list)"
        if annotation.startswith("dict["):
            return "field(default_factory=dict)"
        raise SystemExit(f"a field that may be left out needs a default in the schema: {prop}")

    def value(self, schema: dict, value) -> str:
        """A Python expression for the JSON `value` of a field described by `schema`."""
        inner, _ = nullable(schema)
        if value is None:
            return "None"
        name = ref_name(inner)
        if name == "Decimal":
            return f"decimal.Decimal({json.dumps(str(value))})"
        if name == "Date":
            return f"datetime.date.fromisoformat({json.dumps(value)})"
        target = self.defs.get(name) if name else None
        if target and "properties" in target and isinstance(value, dict):
            props = target["properties"]
            args = ", ".join(f"{attr(k)}={self.value(props.get(k, {}), v)}" for k, v in value.items())
            return f"{name}({args})"
        if isinstance(value, list):
            items = inner.get("items", {})
            return "[" + ", ".join(self.value(items, v) for v in value) + "]"
        if isinstance(value, str):
            return json.dumps(value)
        return repr(value)

    def dataclass(self, name: str, schema: dict, tag: tuple[str, str] | None = None, extra=None) -> None:
        required = set(schema.get("required", []))
        fields = []
        for key, prop in schema.get("properties", {}).items():
            if tag and key == tag[0]:
                continue
            annotation = self.annotation(prop)
            default = None if key in required else self.default(prop, annotation)
            fields.append((key, annotation, default, doc(prop.get("description"))))
        if extra:
            fields.append(extra)
        lines = ["@dataclass(frozen=True, kw_only=True)", f"class {name}:"]
        lines.append(docstring(doc(schema.get("description")), 4))
        if tag:
            lines += ["", f"    {tag[0].upper()}: ClassVar[str] = {json.dumps(tag[1])}"]
            lines.append(f'    """The value of the `{tag[0]}` tag that identifies this variant."""')
        for key, annotation, default, text in fields:
            lines.append("")
            lines.append(f"    {attr(key)}: {annotation}" + (f" = {default}" if default else ""))
            if text:
                lines.append(docstring(text, 4))
        self.blocks.append("\n".join(lines))
        self.classes[name] = name

    def union(self, name: str, variants: list[dict], description: str) -> None:
        tag = tag_of(variants)
        names = {}
        for v in variants:
            value = v["properties"][tag]["const"]
            cls = VARIANT_NAMES.get(name, {}).get(value, pascal(value))
            if cls in self.classes or cls in self.defs:
                raise SystemExit(f"variant name {cls} of {name} clashes with another type")
            names[value] = cls
            self.dataclass(cls, v, tag=(tag, value))
        members = ", ".join(names.values())
        self.blocks.append(f"{name} = Union[{members}]\n" + docstring(doc(description), 0))
        self.unions[name] = (tag, names)

    def build(self) -> str:
        literals = []
        for name in sorted(self.defs):
            schema = self.defs[name]
            if name in SCALARS:
                continue
            if is_string_enum(schema):
                literals.append(f"{name} = {self.inner(schema)}\n" + docstring(doc(schema.get("description")), 0))
            elif "oneOf" in schema and "properties" in schema:
                field_name, union = FLATTENED[name]
                self.union(union, schema["oneOf"], f"The kind of a {name.lower()}, with its fields.")
                self.flattened[name] = (field_name, union)
                self.dataclass(name, schema, extra=(field_name, union, None, f"What the {name.lower()} does."))
            elif "oneOf" in schema:
                self.union(name, schema["oneOf"], schema.get("description", ""))
            elif "properties" in schema:
                self.dataclass(name, schema)
        aliases = [
            f"{name} = {SCALARS[name][0]}\n" + docstring(SCALARS[name][2], 0)
            for name in SCALARS
            if SCALARS[name][0] == "str"
        ]
        unions = {k: (tag, dict(sorted(v.items()))) for k, (tag, v) in sorted(self.unions.items())}
        table_unions = ",\n".join(
            f"    {json.dumps(k)}: ({json.dumps(tag)}, {{"
            + ", ".join(f"{json.dumps(t)}: {c}" for t, c in v.items())
            + "})"
            for k, (tag, v) in unions.items()
        )
        table_flat = ", ".join(f"{json.dumps(k)}: ({json.dumps(f)}, {json.dumps(u)})" for k, (f, u) in self.flattened.items())
        names = sorted([*self.classes, *self.unions, *[n for n in self.defs if is_string_enum(self.defs[n]) and n not in SCALARS], *[n for n in SCALARS if SCALARS[n][0] == "str"]])
        header = f'"""Data types exchanged with the Finalytics engine.\n\n{HEADER}\n"""'
        parts = [
            header,
            "from __future__ import annotations\n\nimport datetime\nimport decimal\nfrom dataclasses import dataclass, field\nfrom typing import ClassVar, Literal, Union",
            "\n\n".join(aliases),
            "\n\n".join(literals),
            "\n\n\n".join(self.blocks),
            "# The tag property and the class of each variant, by union.\nUNIONS = {\n" + table_unions + ",\n}",
            "# Types whose fields are flattened together with a union: the field and the union.\nFLATTENED = {" + table_flat + "}",
            "__all__ = [\n" + "".join(f"    {json.dumps(n)},\n" for n in names) + "]",
        ]
        return "\n\n\n".join(parts) + "\n"


def attr(key: str) -> str:
    """The Python attribute for a JSON property: a keyword gets a trailing underscore."""
    return key + "_" if keyword.iskeyword(key) else key


def docstring(text: str, indent: int) -> str:
    """A docstring at `indent`, wrapped to 100 columns, with paragraphs kept."""
    pad = " " * indent
    if not text:
        return ""
    paragraphs = []
    for p in text.split("\n\n"):
        joined = " ".join(line.strip() for line in p.split("\n"))
        paragraphs.append(textwrap.fill(joined, width=100 - indent - 3, break_on_hyphens=False, break_long_words=False))
    body = "\n\n".join(paragraphs)
    if "\n" not in body and len(body) + indent + 6 <= 100:
        return f'{pad}"""{body}"""'
    lines = body.split("\n")
    out = [f'{pad}"""{lines[0]}']
    out += [f"{pad}{line}".rstrip() for line in lines[1:]]
    out.append(f'{pad}"""')
    return "\n".join(out)


def main() -> int:
    defs = json.loads(SCHEMA.read_text())["$defs"]
    outputs = {TYPESCRIPT: typescript(defs), PYTHON: Python(defs).build()}
    check = "--check" in sys.argv
    stale = False
    for path, text in outputs.items():
        current = path.read_text() if path.exists() else ""
        if current == text:
            continue
        if check:
            print(f"{path.relative_to(ROOT)} is out of date; run python scripts/generate-types.py")
            stale = True
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
